// Step 6c-3: independent static ownership + identical scaffold rendering.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'parse5';
import { registry } from '../tools/lib/registry.mjs';
import { keepPage, exitIfNoPages } from './lib/page-filter.mjs';
import { resultRoles, renderResultOverlay } from '../src/platform/shell/render-result-overlays.js';
import { renderGameShell } from '../src/platform/shell/render-game-shell.js';
import { transformResultRegions } from '../tools/lib/result-regions.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFileSync(join(ROOT, path), 'utf8');
const FAMILY = new Set([
    'gravity-slingshot', 'lumen', 'circuit', 'silk-dew', 'bond-forge',
    'echo-cave', 'maxwell-demon', 'crystal-bloom', 'flame-verse', 'ripple-duet',
]);
const all = registry.all();
const participants = all.filter(g => resultRoles(g).length > 0);
assert.equal(participants.length, FAMILY.size, 'all ten historical puzzle games must opt in');
assert.deepEqual(new Set(participants.map(g => g.id)), FAMILY, 'no accidental role additions or omissions');
const selected = participants.filter(g => keepPage(g.id));
exitIfNoPages(selected, 'verify-result-overlays');
const attr = (node, key) => node.attrs?.find(a => a.name === key)?.value;
const classes = node => (attr(node, 'class') || '').split(/\s+/);
const collect = (node, list = []) => {
    if (node.tagName) list.push(node);
    for (const child of node.childNodes || []) collect(child, list);
    return list;
};

let checks = 0;
for (const game of all) {
    const source = read(game.href);
    const roles = resultRoles(game);
    for (const kind of ['clear', 'over']) {
        const begin = '<!-- registry:begin result-' + kind + ' -->';
        const end = '<!-- registry:end result-' + kind + ' -->';
        assert.equal(source.split(begin).length - 1, roles.includes(kind) ? 1 : 0,
            game.id + ': no missing or undeclared begin marker');
        assert.equal(source.split(end).length - 1, roles.includes(kind) ? 1 : 0,
            game.id + ': no missing or undeclared end marker');
    }
    if (!keepPage(game.id) || !roles.length) continue;
    const nodes = collect(parse(source));
    const ids = new Map(nodes.filter(n => attr(n, 'id')).map(n => [attr(n, 'id'), n]));
    assert.equal(ids.size, nodes.filter(n => attr(n, 'id')).length, game.id + ': unique ids');
    for (const kind of roles) {
        const label = game.id + '/' + kind;
        const name = 'result-' + kind;
        const start = source.indexOf('<!-- registry:begin ' + name + ' -->');
        const stop = source.indexOf('<!-- registry:end ' + name + ' -->');
        const indent = source.slice(source.lastIndexOf('\n', start) + 1, start);
        const region = source.slice(source.indexOf('\n', start) + 1, stop);
        assert.equal(region.trimEnd(), renderResultOverlay(game, kind, indent), label + ': generated bytes match');
        const overlay = ids.get(game.prefix + '-' + kind);
        assert(overlay && overlay.tagName === 'div' && classes(overlay).includes('game-overlay'), label + ': overlay node');
        assert(classes(overlay).includes('hidden'), label + ': starts hidden');
        assert.equal(attr(overlay.parentNode, 'class')?.includes('game-stage'), true, label + ': stage-owned');
        const req = kind === 'over'
            ? ['over-title', 'over-score', 'over-sub', 'lb-title', 'lb-list', 'lb-status', 'username-label', 'username',
                'btn-copy', 'btn-menu2', 'btn-again']
            : ['clear-stars', 'clear-line', 'btn-next', 'btn-replay', 'btn-menu1'];
        for (const slot of req) assert(ids.has(game.prefix + '-' + slot), label + ': missing bound ' + slot);
        const buttons = collect(overlay).filter(n => n.tagName === 'button');
        assert.deepEqual(buttons.map(n => attr(n, 'id')), (kind === 'over'
            ? ['btn-copy', 'btn-menu2', 'btn-again'] : ['btn-next', 'btn-replay', 'btn-menu1'])
            .map(suffix => game.prefix + '-' + suffix), label + ': button order and identity');
        if (kind === 'over') {
            assert.equal(attr(ids.get(game.prefix + '-username'), 'maxlength'), '20', label + ': name length');
            assert.equal(attr(ids.get(game.prefix + '-username-label'), 'for'), game.prefix + '-username',
                label + ': label input binding');
        }
        if (game.shell?.styles?.scienceShowcase && kind === 'clear') {
            assert.equal(attr(ids.get(game.prefix + '-clear-status'), 'role'), 'status',
                label + ': campaign announcement');
        }
        checks++;
    }
    // Generator must not rewrite game-owned nodes in a second pass.
    assert.equal(transformResultRegions(source, game).src, source, game.id + ': idempotent registry generation');
    // Scaffold and generator must use the identical authoring source.
    const scaffold = renderGameShell(game);
    for (const kind of roles) {
        const expected = renderResultOverlay(game, kind, '                ');
        assert(scaffold.includes(expected), game.id + ': scaffold result rendering matches renderer');
    }
    // The game-owned chemical-bond explanation must never be replaced with a generic clear card.
    if (game.id === 'bond-forge') {
        assert(ids.has('bf-clear-note'), 'bond forge keeps its custom clear note');
        assert(!source.includes('registry:begin result-clear'), 'bond forge clear remains game owned');
        assert(!classes(ids.get('bf-over-score')).includes('game-over-score'), 'legacy Bond Forge CSS unchanged');
    }
    // First-time installs with an ID-less custom child must refuse ownership.
    const unmarked = source.replace(/^[ \t]*<!-- registry:(?:begin|end) result-(?:over|clear) -->\r?\n/gm, '');
    const target = '<div class="' + game.prefix + '-over-sub';
    const mutated = unmarked.replace(target, '<span data-foreign="1">owned by the game</span>\n' + target);
    assert.notEqual(mutated, unmarked, game.id + ': mutation fixture inserted');
    assert.throws(() => transformResultRegions(mutated, game), /initial migration would change DOM/,
        game.id + ': new game-owned content cannot be silently erased');
}
console.log('verify-result-overlays: ' + checks + ' generated overlays; independent bindings, ordering and mutation guards passed');
