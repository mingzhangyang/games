export const DAILY_POOL = DAILY_SPECS.map(spec => buildLevel(spec));

export const DAILY_RULES = Object.freeze({ parMin: 4, parMax: 6, minForesight: 2, attempts: 400 });

const dailySpaces = new Map();

/**
 * 当日谜题（确定性，全球同题）。
 * 种子 = FNV-1a('lumen-' + dateKey)；dateKey 为 src/platform/daily.js 的 UTC+8 紧凑日期。
 * 布局 = 种子 % 池大小；初盘 = solver.scramble(mulberry32(种子))，解态改写为离初盘最近的唯一解。
 */
export function dailyLevel(dateKey) {
    const seed = hashStringFNV('lumen-' + dateKey);
    const layout = seed % DAILY_POOL.length;
    const def = DAILY_POOL[layout];
    let space = dailySpaces.get(layout);
    if (!space) {
        space = solveSpace(def);
        dailySpaces.set(layout, space);
    }
    const pick = scramble(space, mulberry32(seed), DAILY_RULES);
    return {
        id: 'daily',
        sol: gridOfMask(space.units, def.sol, pick.target),
        grid: gridOfMask(space.units, def.sol, pick.mask),
        split: def.split,
        links: def.links,
        par: pick.par,
        foresight: pick.foresight,
        dateKey,
        layout,
    };
}
