#!/usr/bin/env node
/** Exhaustively proves every curated board and writes stable runtime metadata. */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CHAPTER_SOURCE, LEVEL_SOURCE } from '../../src/games/magnetic-garden/model/level-source.js';
import { RULES_VERSION, validateLevel } from '../../src/games/magnetic-garden/model/rules.js';
import { solveLevel } from '../../src/games/magnetic-garden/model/solver.js';

const output = fileURLToPath(new URL('../../src/games/magnetic-garden/model/levels.js', import.meta.url));
function literal(value) {
    if (value === null) return 'null';
    if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`;
    if (typeof value === 'object') return `{ ${Object.entries(value).map(([key, item]) => `${key}: ${literal(item)}`).join(', ')} }`;
    return String(value);
}
const levels = LEVEL_SOURCE.map(level => {
    const errors = validateLevel(level);
    if (errors.length) throw new Error(`${level.id}: ${errors.join(' ')}`);
    const proof = solveLevel(level, { maxStates: 100000 });
    if (proof.status !== 'solved') throw new Error(`${level.id}: ${proof.status} (${proof.reason || 'exhausted frontier'})`);
    console.log(`${level.id}: optimal ${proof.depth}, ${proof.visited} visited states`);
    return {
        ...level,
        par: proof.depth,
        excellent: proof.depth + 2,
        solution: proof.solution,
        proof: { algorithm: 'breadth-first', rulesVersion: RULES_VERSION, visited: proof.visited, optimal: true },
    };
});
const chapters = CHAPTER_SOURCE.map(chapter => ({ ...chapter, levelIds: levels.filter(level => level.chapter === chapter.id).map(level => level.id) }));
const source = `// Generated by tools/generators/magnetic-garden-levels.mjs. Edit level-source.js instead.\nexport const CHAPTERS = [\n${chapters.map(chapter => `    ${literal(chapter)},`).join('\n')}\n];\n\nexport const LEVELS = [\n${levels.map(level => `    ${literal(level)},`).join('\n')}\n];\n\nexport function getLevel(id) {\n    return LEVELS.find(level => level.id === id);\n}\n`;
if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source) throw new Error('Magnetic Garden level metadata is stale. Run node tools/generators/magnetic-garden-levels.mjs.');
} else {
    fs.writeFileSync(output, source);
}
